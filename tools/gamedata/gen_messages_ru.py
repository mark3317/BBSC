BATTLE = re.compile(r'^The host started the battle against\n(<\?npcNameId@\d+\?>)\.$')
DEFEATED = re.compile(r'^(<\?npcNameId@\d+\?>) defeated\.$')


def russian(text):
    if text in RU:
        return RU[text]
    if m := BATTLE.match(text):
        return 'Хост начал битву с боссом:\n' + m[1] + '.'
    if m := DEFEATED.match(text):
        return 'Побеждён: ' + m[1] + '.'
    for opening, lore in LORE.items():
        if text.startswith(opening):
            return lore
    raise SystemExit('no Russian text for %r' % text)


def unescape(cpp):
    return cpp.encode('latin-1', 'backslashreplace').decode('unicode_escape') if '\\' in cpp else cpp


def cpp(text):
    return text.replace('\\', '\\\\').replace('"', '\\"').replace('\n', '\\n')


def main():
    lines = open(SOURCE, encoding='utf-8').read().splitlines()
    entry = re.compile(r'^\{(\d+), (\d+), u"((?:[^"\\]|\\.)*)"\},')
    out = ['// Generated by tools/gamedata/gen_messages_ru.py from bbsc_messages.inc - do not edit.',
           '// {category, message id, BBSC text in Russian}   // BBSC English text',
           '// Same entries, same order as bbsc_messages.inc.']
    count = 0
    for line in lines:
        m = entry.match(line)
        if not m:
            continue
        english = m[3].replace('\\n', '\n').replace('\\"', '"').replace("\\'", "'").replace('\\\\', '\\')
        out.append('{%s, %s, u"%s"}, // %s' % (m[1], m[2], cpp(russian(english)),
                                              cpp(english)[:90].rstrip('\\')))
        count += 1
    with open(OUT, 'w', encoding='utf-8', newline='\n') as f:
        f.write('\n'.join(out) + '\n')
    print('%d Russian messages -> %s' % (count, OUT))


if __name__ == '__main__':
    main()
